#!/usr/bin/env python3
"""Write app/assets/licenses.js: the licenses of all software built into QCalc, shown in the app
(menu > About this app > Open source licenses; in Japanese このアプリについて > オープンソースライセンス).
The names of the licenses are in English and in Japanese (license / license_ja, titles / titles_ja).

Run it after fetch-sources.sh when a library version changes. It reads the license files from
src/ (the upstream sources) and from the zig package that build-engine.sh compiles with
(musl, libc++, libc++abi, libunwind and compiler_rt are compiled into the engine from zig's copies).
"""
import json
import os
import sys

P = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(P, 'src')
try:
    import ziglang
    ZIG = os.path.dirname(ziglang.__file__)
except ImportError:
    sys.exit('ziglang is not installed (pip install ziglang==0.17.1)')


def read(*parts):
    with open(os.path.join(*parts), encoding='utf-8') as f:
        return f.read().replace('\r\n', '\n').strip('\n') + '\n'


texts = {
    'gpl2': read(SRC, 'libqalculate-5.13.2', 'COPYING'),
    'gpl3': read(SRC, 'mpfr-4.2.2', 'COPYING'),
    'lgpl3': read(SRC, 'mpfr-4.2.2', 'COPYING.LESSER'),
    'libxml2': read(SRC, 'libxml2-2.15.4', 'Copyright'),
    'musl': read(ZIG, 'lib', 'libc', 'musl', 'COPYRIGHT'),
    'llvm': read(ZIG, 'lib', 'libcxx', 'LICENSE.TXT'),
    'zig': read(ZIG, 'LICENSE'),
}
titles = {
    'gpl2': 'GNU General Public License v2',
    'gpl3': 'GNU General Public License v3',
    'lgpl3': 'GNU Lesser General Public License v3',
    'libxml2': 'libxml2 license (MIT)',
    'musl': 'musl license (MIT)',
    'llvm': 'Apache License v2.0 with LLVM Exceptions',
    'zig': 'Zig license (MIT)',
}
titles_ja = {
    'libxml2': 'libxml2 のライセンス（MIT）',
    'musl': 'musl のライセンス（MIT）',
    'zig': 'Zig のライセンス（MIT）',
}
components = [
    {'name': 'QCalc', 'version': '',
     'license': 'GNU GPL v2 or later', 'license_ja': 'GNU GPL v2 以降',
     'copyright': 'Copyright (C) 2026 HiroshiTsu',
     'url': 'https://github.com/HiroshiTsu/qcalc', 'texts': ['gpl2']},
    {'name': 'libqalculate', 'version': '5.13.2',
     'license': 'GNU GPL v2 or later', 'license_ja': 'GNU GPL v2 以降',
     'copyright': 'Copyright (C) 2003-2007, 2008, 2016-2024 Hanna Knutsson',
     'url': 'https://github.com/Qalculate/libqalculate', 'texts': ['gpl2']},
    {'name': 'GNU MP (GMP)', 'version': '6.3.0',
     'license': 'GNU LGPL v3 or later, or GNU GPL v2 or later', 'license_ja': 'GNU LGPL v3 以降、または GNU GPL v2 以降',
     'copyright': 'Copyright 1991, 1993-1997, 1999-2016, 2020, 2021 Free Software Foundation, Inc.',
     'url': 'https://gmplib.org/', 'texts': ['lgpl3', 'gpl3', 'gpl2']},
    {'name': 'GNU MPFR', 'version': '4.2.2',
     'license': 'GNU LGPL v3 or later', 'license_ja': 'GNU LGPL v3 以降',
     'copyright': 'Copyright 1999-2025 Free Software Foundation, Inc.',
     'url': 'https://www.mpfr.org/', 'texts': ['lgpl3', 'gpl3']},
    {'name': 'libxml2', 'version': '2.15.4',
     'license': 'MIT License', 'license_ja': 'MIT ライセンス',
     'copyright': 'Copyright (C) 1998-2012 Daniel Veillard. Copyright (C) The Libxml2 Contributors.',
     'url': 'https://gitlab.gnome.org/GNOME/libxml2', 'texts': ['libxml2']},
    {'name': 'musl libc', 'version': '(from Zig 0.17.1)', 'version_ja': '（Zig 0.17.1 に同梱）',
     'license': 'MIT License', 'license_ja': 'MIT ライセンス',
     'copyright': 'Copyright © 2005-2020 Rich Felker, et al.',
     'url': 'https://musl.libc.org/', 'texts': ['musl']},
    {'name': 'LLVM libc++ / libc++abi / libunwind', 'version': '(from Zig 0.17.1)', 'version_ja': '（Zig 0.17.1 に同梱）',
     'license': 'Apache License v2.0 with LLVM Exceptions',
     'copyright': 'LLVM Project contributors',
     'url': 'https://llvm.org/', 'texts': ['llvm']},
    {'name': 'Zig compiler_rt', 'version': '0.17.1',
     'license': 'MIT License', 'license_ja': 'MIT ライセンス',
     'copyright': 'Copyright (c) Zig contributors',
     'url': 'https://ziglang.org/', 'texts': ['zig']},
]
data = {'components': components, 'titles': titles, 'titles_ja': titles_ja, 'texts': texts}
js = json.dumps(data, ensure_ascii=False, indent=1)
js = js.replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
out = os.path.join(P, 'app', 'assets', 'licenses.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by make-licenses.py: licenses of the software built into QCalc.\n')
    f.write('window.QCALC_LICENSES = ' + js + ';\n')
print(out, os.path.getsize(out), 'bytes')
